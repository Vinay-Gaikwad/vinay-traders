const reverseUiTranslations = Object.fromEntries(Object.entries(uiTranslations).map(([english, marathi]) => [marathi, english]))

export function localizeText(value: string, language: Language): string {
  const replacements = language === 'mr' ? uiTranslations : reverseUiTranslations
  return Object.entries(replacements).sort((a, b) => b[0].length - a[0].length).reduce((text, [from, to]) => text.split(from).join(to), value)
}

export function localizeDocument(language: Language): void {
  if (typeof document === 'undefined') return
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT)
  const nodes: Text[] = []
  let node: Node | null
  while ((node = walker.nextNode())) nodes.push(node as Text)
  for (const textNode of nodes) {
    const parent = textNode.parentElement
    if (!parent || ['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(parent.tagName)) continue
    const translated = localizeText(textNode.nodeValue ?? '', language)
    if (translated !== textNode.nodeValue) textNode.nodeValue = translated
  }
  for (const element of Array.from(document.querySelectorAll<HTMLElement>('[placeholder], [aria-label], [title]'))) {
    for (const attribute of ['placeholder', 'aria-label', 'title']) {
      const value = element.getAttribute(attribute)
      if (value) {
        const translated = localizeText(value, language)
        if (translated !== value) element.setAttribute(attribute, translated)
      }
    }
  }
}

